#!/bin/bash
# Build the NX769J GPU userland for iOS 16 arm64 on macOS with Xcode:
#   - NativeAdrenoMetal.bundle: UniXNU NativeMetal c6d29ca adapted by data-a-live's adapt_ios16.py, with the metal2vulkan
#     720ef1ce runtime (NativeMetal's bridge patches, then data-a-live's m2v patches) as a Rust static library
#   - vktest: data-a-live's Vulkan test (compute fill, triangle) against Turnip
#   - mtltest: data-a-live's Metal test (needs Xcode's Metal toolchain; skipped without it)
# The recipe follows third_party/data-a-live/metal/build_plugin.sh and vktest/build_ios.sh (MIT). Every input is pinned:
#
#   .cache/gpu-user/nativemetal          git archive of UniXNU drivers/AdrenoMetal at c6d29caad6d880cc8204ebe3bc34d77479a3255d
#   .cache/gpu-user/metal2vulkan         steelbrain/metal2vulkan at 720ef1ce9ae2a2068999a8675717418b9416283e
#   .cache/gpu-user/AdrenoPM4            UniXNU kits/AdrenoPM4 at 445f8fe6d115738352b9d78dc70af6d61aa7f62f
#   .cache/gpu-user/NativeMobileDisplay  NativeGOPWire.h of UniXNU drivers/GopFramebuffer at 8666a9950c9699b368931d18cac92c0fdb2ce9c0
#   $UNIXNU/.cache/mesa-work             Mesa 85fda3b with UniXNU's patches (Vulkan headers)
#   $UNIXNU/build/mesa-tu-ios16          Turnip from UniXNU scripts/build-turnip-darwin.py --target ios16
#   $UNIXNU/drivers/Adreno740            NativeAdrenoABI.h (version 2, what the kernel's NativeAdrenoPublish serves)
#
#   scripts/build-nx769j-metal.sh [UNIXNU]
# Output: .cache/gpu-user/out (bundle, libvulkan_freedreno.dylib, vktest, mtltest, SHA256SUMS). Nothing here is committed.
set -euo pipefail
D=$(cd "$(dirname "$0")/.." && pwd)
U=$(cd "${1:-$D/../UniXNU}" && pwd)
C=$D/.cache/gpu-user
OUT=$C/out
B=$OUT/build
TP=$D/third_party/data-a-live
for need in "$C/nativemetal" "$C/metal2vulkan/.git" "$C/AdrenoPM4/AdrenoPM4.c" "$C/NativeMobileDisplay/NativeGOPWire.h" \
	"$U/.cache/mesa-work/include/vulkan" "$U/build/mesa-tu-ios16/src/freedreno/vulkan/libvulkan_freedreno.dylib" \
	"$U/drivers/Adreno740/NativeAdrenoABI.h"; do
	[ -e "$need" ] || { echo "missing input: $need" >&2; exit 2; }
done
[ "$(git -C "$C/metal2vulkan" rev-parse HEAD)" = 720ef1ce9ae2a2068999a8675717418b9416283e ] || { echo "metal2vulkan pin differs" >&2; exit 2; }
rm -rf "$OUT"; mkdir -p "$B/gen"
SDK=$(xcrun --sdk iphoneos --show-sdk-path)
BASE=(-target arm64-apple-ios16.0 -isysroot "$SDK" -O2 -g -fstack-protector-strong)

echo "== NativeMetal c6d29ca for iOS 16 (adapt_ios16.py)"
NM=$C/nativemetal-work
rm -rf "$NM"; cp -R "$C/nativemetal" "$NM"
python3 "$TP/metal/adapt_ios16.py" "$NM" > "$B/adapt.log"
grep -c edited "$B/adapt.log"

echo "== smoke shaders"
{
	echo '// Generated by scripts/build-nx769j-metal.sh from NativeMetal/shaders; do not edit.'
	echo '#pragma once'
	echo '#include <stdint.h>'
	for s in "$NM"/shaders/smoke_*; do
		n=$(basename "$s")
		glslc --target-env=vulkan1.1 -O "$s" -o "$B/$n.spv"
		spirv-val --target-env vulkan1.1 "$B/$n.spv"
		python3 -c 'import struct,sys; d=open(sys.argv[1],"rb").read(); w=struct.unpack("<%dI" % (len(d)//4), d)
print("static const uint32_t kSpv_%s[] = {" % sys.argv[2].replace(".", "_"))
for i in range(0, len(w), 8): print("    " + ", ".join("0x%08x" % x for x in w[i:i+8]) + ",")
print("};")' "$B/$n.spv" "$n"
	done
} > "$B/gen/NativeTurnipShaders.h"

echo "== metal2vulkan bridge (NativeMetal bridge patches)"
M2V=$C/metal2vulkan-work
rm -rf "$M2V"; cp -R "$C/metal2vulkan" "$M2V"
# NativeMetal's bridge patches, then data-a-live's runtime changes (made against the tree after NativeMetal's; the
# iOS 16 bridge edits of adapt_ios16.py use their fields).
for p in "$NM"/bridge/patches/000*.patch "$TP"/m2v/[0-9][0-9][0-9][0-9]-*.patch; do
	echo "   $(basename "$p")"
	git -C "$M2V" apply "$p"
done
LLVM_AS=$(brew --prefix llvm)/bin/llvm-as
"$LLVM_AS" -o "$B/runtime_examples.air" "$M2V/crates/metal2vulkan-validation/fixtures/public/examples/runtime_examples.ll"
"$LLVM_AS" -o "$B/function_constant.air" "$M2V/crates/metal2vulkan-validation/fixtures/public/kernel_function_constant_gate_fold.ll"
cat > "$B/Cargo.toml" <<EOF
[package]
name = "native-metal-bridge"
version = "0.1.0"
edition = "2024"
rust-version = "1.98"
[workspace]
[lib]
crate-type = ["staticlib"]
path = "$NM/bridge/NativeMetalBridge.rs"
[dependencies]
metal2vulkan = { path = "$M2V/crates/metal2vulkan", features = ["ash"] }
metal2vulkan-runtime = { path = "$M2V/crates/metal2vulkan-runtime" }
libc = "0.2"
sha2 = { version = "0.10", features = ["asm"] }
[profile.release]
panic = "unwind"
debug = 1
EOF
RID=$( (git -C "$M2V" rev-parse HEAD; git -C "$M2V" diff HEAD) | shasum -a 256 | cut -c1-32)
NMB_RUNTIME_ID=$RID NMB_FIXTURE_AIR=$B/runtime_examples.air NMB_FC_AIR=$B/function_constant.air \
	IPHONEOS_DEPLOYMENT_TARGET=16.0 AR=/usr/bin/ar \
	cargo +1.98.0 build --release --manifest-path "$B/Cargo.toml" --target aarch64-apple-ios --target-dir "$C/cargo-target"
BRIDGE=$C/cargo-target/aarch64-apple-ios/release/libnative_metal_bridge.a
ls -l "$BRIDGE"

echo "== plugin bundle"
BUNDLE=$OUT/NativeAdrenoMetal.bundle
mkdir -p "$BUNDLE"
xcrun clang "${BASE[@]}" -std=c11 -c "$C/AdrenoPM4/AdrenoPM4.c" -o "$B/AdrenoPM4.o"
xcrun clang++ "${BASE[@]}" -std=c++17 -fobjc-arc -Wno-deprecated-declarations -bundle \
	-I "$U/drivers/Adreno740" -I "$C/AdrenoPM4" -I "$U/.cache/mesa-work/include" -I "$B/gen" \
	-x objective-c++ "$NM/NativeAdrenoMetalPlugin.mm" "$NM/NativeBridgeMetalFrontend.mm" -x none \
	"$B/AdrenoPM4.o" "$BRIDGE" -Wl,-dead_strip -lobjc -framework Foundation -framework Metal -framework IOSurface \
	-o "$BUNDLE/NativeAdrenoMetal"
xcrun strip -x "$BUNDLE/NativeAdrenoMetal"
rm -rf "$BUNDLE/NativeAdrenoMetal.dSYM"
plutil -create xml1 "$BUNDLE/Info.plist"
for kv in CFBundleIdentifier=com.unixnu.nx769j.NativeAdrenoMetal CFBundleExecutable=NativeAdrenoMetal \
	CFBundlePackageType=BNDL CFBundleVersion=1 CFBundleShortVersionString=1 \
	NSPrincipalClass=NativeAdrenoMetalDevice MinimumOSVersion=16.0; do
	plutil -insert "${kv%%=*}" -string "${kv#*=}" "$BUNDLE/Info.plist"
done
codesign -s - -f --pagesize 4096 --identifier com.unixnu.nx769j.NativeAdrenoMetal "$BUNDLE/NativeAdrenoMetal"

echo "== Turnip and vktest"
TU=$OUT/libvulkan_freedreno.dylib
cp "$U/build/mesa-tu-ios16/src/freedreno/vulkan/libvulkan_freedreno.dylib" "$TU"
install_name_tool -id /usr/lib/libvulkan_freedreno.dylib "$TU"
xcrun strip -x "$TU"
glslangValidator -V --target-env vulkan1.1 --vn fill_spv -o "$B/fill_spv.h" "$TP/vktest/fill.comp" > /dev/null
glslangValidator -V --target-env vulkan1.1 --vn tri_vert_spv -o "$B/tri_vert_spv.h" "$TP/vktest/tri.vert" > /dev/null
glslangValidator -V --target-env vulkan1.1 --vn tri_frag_spv -o "$B/tri_frag_spv.h" "$TP/vktest/tri.frag" > /dev/null
# NX769J: Turnip inside the plugin bundle (/usr/lib is on the sealed system volume), mtltest from the GPU addon, and extra
# TU_DEBUG flags from the boot-arg nx769j-tudebug=<csv> so a Turnip debug flag can be tried without rebuilding the userland.
python3 - "$TP/vktest/vktest.c" "$B/vktest.c" <<'PY'
import sys
s = open(sys.argv[1]).read()
s = s.replace('#define DRIVER "/usr/lib/libvulkan_freedreno.dylib"',
              '#define DRIVER "/System/Library/Extensions/NativeAdrenoMetal.bundle/libvulkan_freedreno.dylib"')
s = s.replace('#define MTLTEST "/usr/libexec/mtltest"', '#define MTLTEST "/private/var/ngpu/bin/mtltest"')
old = '\tsetenv("TU_DEBUG", "sysmem,nocb", 1);     /* no GMEM binning, no concurrent binning yet */'
new = ('\t{\n'
       '\t\tchar td[256] = "sysmem,nocb";   /* no GMEM binning, no concurrent binning yet */\n'
       '\t\tconst char *extra = strstr(args, "nx769j-tudebug=");\n'
       '\t\tif (extra) {\n'
       '\t\t\textra += sizeof("nx769j-tudebug=") - 1;\n'
       '\t\t\tsize_t k = strlen(td); td[k++] = \',\';\n'
       '\t\t\twhile (*extra && *extra != \' \' && k < sizeof(td) - 1) td[k++] = *extra++;\n'
       '\t\t\ttd[k] = 0;\n'
       '\t\t}\n'
       '\t\tsetenv("TU_DEBUG", td, 1);\n'
       '\t\tsay("VKTEST: TU_DEBUG=%s", td);\n'
       '\t}')
assert s.count(old) == 1, 'TU_DEBUG anchor not found'
open(sys.argv[2], 'w').write(s.replace(old, new))
PY
grep -q 'NativeAdrenoMetal.bundle/libvulkan_freedreno.dylib' "$B/vktest.c" && grep -q 'ngpu/bin/mtltest' "$B/vktest.c" && grep -q 'nx769j-tudebug' "$B/vktest.c"
xcrun clang -target arm64-apple-ios16.0 -isysroot "$SDK" -O2 -Wall -I "$U/.cache/mesa-work/include" -I "$B" \
	"$B/vktest.c" -o "$OUT/vktest"
# The test programs open the accelerator's user client: the grant UniXNU's probe daemon carries (adrenoprobed-entitlements).
cat > "$B/test-entitlements.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>com.apple.private.security.no-container</key><true/>
<key>com.apple.security.iokit-user-client-class</key><array><string>AGXDeviceUserClient</string></array>
</dict></plist>
PLIST
cp "$TU" "$BUNDLE/libvulkan_freedreno.dylib"
codesign -s - -f --pagesize 4096 "$TU" "$BUNDLE/libvulkan_freedreno.dylib"
codesign -s - -f --pagesize 4096 --entitlements "$B/test-entitlements.plist" "$OUT/vktest"

if xcrun -sdk iphoneos metal -v > /dev/null 2>&1; then
	echo "== mtltest"
	xcrun -sdk iphoneos metal -mios-version-min=16.0 -c "$TP/metal/mtltest.metal" -o "$B/mtltest.air"
	xcrun -sdk iphoneos metallib "$B/mtltest.air" -o "$B/mtltest.metallib"
	(cd "$B" && xxd -i mtltest.metallib > gen/mtltest_metallib.h)
	xcrun clang "${BASE[@]}" -fobjc-arc -Wall -I "$B/gen" -I "$TP/metal" "$TP/metal/mtltest.m" \
		-framework Foundation -framework Metal -framework IOSurface -o "$OUT/mtltest"
	codesign -s - -f --pagesize 4096 --entitlements "$B/test-entitlements.plist" "$OUT/mtltest"
else
	echo "== mtltest skipped: Xcode's Metal toolchain is not installed (xcodebuild -downloadComponent MetalToolchain)"
fi

(cd "$OUT" && shasum -a 256 NativeAdrenoMetal.bundle/NativeAdrenoMetal NativeAdrenoMetal.bundle/Info.plist \
	NativeAdrenoMetal.bundle/libvulkan_freedreno.dylib vktest $( [ -e mtltest ] && echo mtltest ) > SHA256SUMS && cat SHA256SUMS)
